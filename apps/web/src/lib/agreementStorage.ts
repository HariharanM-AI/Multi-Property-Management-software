/**
 * Save Checkout Agreement (Property Handover & Security Deposit Settlement) to localStorage
 */
export function saveCheckoutAgreement(data: CheckoutAgreementData): void {
  if (typeof window === 'undefined') return;

  try {
    const raw = localStorage.getItem(CHECKOUT_STORAGE_KEY);
    const store: Record<string, CheckoutAgreementData> = raw ? JSON.parse(raw) : {};

    const cleanUnit = cleanUnitKey(data.unitOrBedName);
    const record: CheckoutAgreementData = {
      ...data,
      isExecuted: true,
      signedAt: data.signedAt || new Date().toISOString(),
    };

    if (data.id) store[`id:${data.id}`] = record;
    if (data.stayId) store[`stay:${data.stayId}`] = record;
    if (data.leaseId) store[`lease:${data.leaseId}`] = record;
    if (data.recordId) store[`record:${data.recordId}`] = record;
    if (data.bedId) store[`bed:${data.bedId}`] = record;
    if (data.unitId) store[`unit:${data.unitId}`] = record;
    if (data.tenantId) store[`tenant:${data.tenantId}`] = record;

    if (data.tenantName) {
      store[`name:${normalizeKey(data.tenantName)}`] = record;
      if (cleanUnit) {
        store[`direct:${normalizeKey(data.tenantName)}_${cleanUnit}`] = record;
      }
    }

    localStorage.setItem(CHECKOUT_STORAGE_KEY, JSON.stringify(store));

    // Also store in unified agreement signatures store for complete signature history
    try {
      const agrStoreRaw = localStorage.getItem(STORAGE_KEY);
      const agrStore: Record<string, StoredAgreementSignature> = agrStoreRaw ? JSON.parse(agrStoreRaw) : {};
      const sigRecord: StoredAgreementSignature = {
        signerName: data.tenantName,
        signerEmail: data.tenantEmail,
        signatureImage: data.residentSignature,
        signedAt: record.signedAt || new Date().toISOString(),
        agreementType: data.propertyType === 'RENTAL_HOUSE' ? 'RENTAL_CHECKOUT_AGREEMENT' : 'PG_CHECKOUT_AGREEMENT',
        isSigned: true,
        isExecuted: true,
        witnesses: data.witnesses,
        stayId: data.stayId,
        leaseId: data.leaseId,
        recordId: data.recordId,
        bedId: data.bedId,
        unitId: data.unitId,
        tenantId: data.tenantId,
        tenantName: data.tenantName,
        tenantPhone: data.tenantPhone,
        tenantEmail: data.tenantEmail,
        tenantAddress: data.tenantAddress,
        tenantAadhaar: data.tenantAadhaar,
        unitName: data.unitOrBedName,
        propertyName: data.propertyName,
        propertyAddress: data.propertyAddress,
        propertyType: data.propertyType,
        securityDeposit: data.initialDeposit,
        startDate: data.originalStartDate,
        checkOutDate: data.checkOutDate,
        sharingType: data.sharingType,
        ownerName: data.ownerName,
        ownerPhone: data.ownerPhone,
        ownerAddress: data.ownerAddress,
        ownerSignature: data.ownerSignature,
      };
      if (data.stayId) agrStore[`record:stay-checkout-${data.stayId}`] = sigRecord;
      if (data.leaseId) agrStore[`record:lease-checkout-${data.leaseId}`] = sigRecord;
      if (data.id) agrStore[`record:checkout-${data.id}`] = sigRecord;
      if (data.tenantName && cleanUnit) agrStore[`checkout_direct:${normalizeKey(data.tenantName)}_${cleanUnit}`] = sigRecord;
      localStorage.setItem(STORAGE_KEY, JSON.stringify(agrStore));
    } catch {}

    // Update tenancy events so all cross-page listeners update in real time
    try {
      localStorage.setItem(
        'propertyos_last_tenancy_event',
        JSON.stringify({
          type: 'CHECKOUT_AGREEMENT_UPDATED',
          timestamp: Date.now(),
          record,
        })
      );
      localStorage.setItem(
        'propertyos_checkout_event',
        JSON.stringify({
          type: 'CHECKOUT_AGREEMENT_UPDATED',
          timestamp: Date.now(),
          record,
        })
      );
    } catch {}

    try {
      window.dispatchEvent(new CustomEvent('checkout_agreement_updated', { detail: record }));
      window.dispatchEvent(new CustomEvent('propertyos_tenancy_event', { detail: record }));
      const bc = new BroadcastChannel('propertyos_realtime_events');
      bc.postMessage({ type: 'CHECKOUT_AGREEMENT_UPDATED', payload: record });
      bc.close();
    } catch {}
  } catch (err) {
    console.error('Failed to save checkout agreement:', err);
  }
}

/**
 * Retrieve Checkout Agreement by stayId, leaseId, recordId, bedId, or tenant details.
 */
export function getCheckoutAgreement(lookup: string | {
  id?: string;
  stayId?: string;
  leaseId?: string;
  recordId?: string;
  bedId?: string;
  unitId?: string;
  tenantId?: string;
  tenantName?: string;
  unitName?: string;
}): CheckoutAgreementData | null {
  if (typeof window === 'undefined' || !lookup) return null;

  try {
    const raw = localStorage.getItem(CHECKOUT_STORAGE_KEY);
    if (!raw) return null;
    const store: Record<string, CheckoutAgreementData> = JSON.parse(raw);

    if (typeof lookup === 'string') {
      if (store[lookup]) return store[lookup];
      const cleanLookup = lookup.replace(/^(stay|lease|record|bed|unit|tenant|name|id):/i, '');
      if (store[`stay:${cleanLookup}`]) return store[`stay:${cleanLookup}`];
      if (store[`lease:${cleanLookup}`]) return store[`lease:${cleanLookup}`];
      if (store[`record:${cleanLookup}`]) return store[`record:${cleanLookup}`];
      if (store[`id:${cleanLookup}`]) return store[`id:${cleanLookup}`];
      if (store[`bed:${cleanLookup}`]) return store[`bed:${cleanLookup}`];
      if (store[`unit:${cleanLookup}`]) return store[`unit:${cleanLookup}`];
      if (store[`tenant:${cleanLookup}`]) return store[`tenant:${cleanLookup}`];
      if (store[`name:${normalizeKey(cleanLookup)}`]) return store[`name:${normalizeKey(cleanLookup)}`];
      return null;
    }

    let found: CheckoutAgreementData | null = null;
    if (lookup.id && store[`id:${lookup.id}`]) found = store[`id:${lookup.id}`];
    else if (lookup.stayId && store[`stay:${lookup.stayId}`]) found = store[`stay:${lookup.stayId}`];
    else if (lookup.leaseId && store[`lease:${lookup.leaseId}`]) found = store[`lease:${lookup.leaseId}`];
    else if (lookup.recordId && store[`record:${lookup.recordId}`]) found = store[`record:${lookup.recordId}`];

    if (!found) {
      const cleanUnit = cleanUnitKey(lookup.unitName);
      if (lookup.tenantName && cleanUnit && store[`direct:${normalizeKey(lookup.tenantName)}_${cleanUnit}`]) {
        found = store[`direct:${normalizeKey(lookup.tenantName)}_${cleanUnit}`];
      }
      if (!found && lookup.tenantId && store[`tenant:${lookup.tenantId}`]) {
        found = store[`tenant:${lookup.tenantId}`];
      }
      if (!found && lookup.tenantName && store[`name:${normalizeKey(lookup.tenantName)}`]) {
        found = store[`name:${normalizeKey(lookup.tenantName)}`];
      }
      if (!found && lookup.bedId && store[`bed:${lookup.bedId}`]) {
        found = store[`bed:${lookup.bedId}`];
      }
      if (!found && lookup.unitId && store[`unit:${lookup.unitId}`]) {
        found = store[`unit:${lookup.unitId}`];
      }
    }

    if (found) {
      // Ensure real owner signature is applied from ownerProfile if present
      const ownerProf = getOwnerProfile();
      if (!isRealDrawnOrSignedSignature(found.ownerSignature) && isRealDrawnOrSignedSignature(ownerProf.signature)) {
        found.ownerSignature = ownerProf.signature;
      }
      // Ensure real resident signature is applied only if agreement is executed
      if (found.isExecuted && !isRealDrawnOrSignedSignature(found.residentSignature)) {
        const tKey = normalizeKey(found.tenantName);
        if (tKey === 'harim') found.residentSignature = HARI_M_DRAWN_SIG;
        else if (tKey === 'kavinm') found.residentSignature = KAVIN_M_DRAWN_SIG;
        else if (found.tenantName) {
          found.residentSignature = generateRealisticHanddrawnResidentSignature(found.tenantName, found.checkOutDate || found.signedAt);
        }
      }
      return found;
    }

    return null;
  } catch (err) {
    console.error('Failed to get checkout agreement:', err);
    return null;
  }
}

