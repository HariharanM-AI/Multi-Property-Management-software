const STORAGE_KEY = 'propertyos_agreement_signatures';

function normalizeKey(str?: string): string {
  if (!str) return '';
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Standardizes unit or bed keys by removing extra room parentheticals (e.g. "Bed 101-C (Room 101)" -> "bed101c").
 */
export function cleanUnitKey(unitName?: string): string {
  if (!unitName) return '';
  const stripped = unitName.replace(/\s*\([^)]*\)/g, '').replace(/room\s*[0-9a-z]+/gi, '').trim();
  return normalizeKey(stripped);
}

/**
 * Checks whether a given signature data string is an authentic hand-drawn or explicitly typed signature,
 * rather than the synthetic blue cursive SVG text generated by fallback functions.
 */
export function isRealDrawnOrSignedSignature(sig?: string | null): boolean {
  if (!sig || typeof sig !== 'string') return false;
  const trimmed = sig.trim();
  if (!trimmed) return false;

  // Real canvas stroke image (PNG, JPEG, WEBP)
  if (trimmed.startsWith('data:image/png') || trimmed.startsWith('data:image/jpeg') || trimmed.startsWith('data:image/webp')) {
    return true;
  }

  // Explicitly typed name signature
  if (trimmed.startsWith('TYPE:')) {
    return true;
  }

  // If SVG data URL, distinguish real vector drawing from the synthetic text fallback
  if (trimmed.startsWith('data:image/svg+xml')) {
    const decoded = decodeURIComponent(trimmed);
    if (
      decoded.includes('sigGrad') ||
      decoded.includes('Authorized Landlord / Owner') ||
      decoded.includes('Tenant Digital E-Sign') ||
      decoded.includes('Verified E-Sign') ||
      decoded.includes('Resident Digital E-Sign') ||
      decoded.includes('Owner Verified E-Sign') ||
      (decoded.includes('Brush Script MT') && decoded.includes('Dancing Script'))
    ) {
      return false; // Synthetic fallback cursive text
    }
    return true;
  }

  return false;
}

